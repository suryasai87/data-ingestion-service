"""Generated Lakeflow Declarative Pipeline sources for the patterns that are not a managed ingestion definition:
files over SFTP or from a UC volume (Auto Loader), and REST APIs behind a UC HTTP connection.

The generated file is uploaded by the deployment into the service principal's workspace folder and referenced from
the pipeline's `libraries`. Values are embedded as Python literals (repr), never string-formatted into code.
"""
from __future__ import annotations

from typing import Any

HEADER = '''# Generated by the Data Ingestion Service for {rid} (v{version}, config sha256 {hash}). Do not edit: change the request.
from pyspark import pipelines as dp
'''


def _comment(rid: str, cfg: dict[str, Any]) -> str:
    own = cfg.get("ownership") or {}
    return f"Landed by the Data Ingestion Service ({rid}); owner {own.get('owner', '')}; classification {own.get('classification', '')}"


def files(rid: str, version: int, config_hash: str, cfg: dict[str, Any], table_name, sftp: dict[str, Any] | None) -> str:
    """Auto Loader: one streaming table per file set. SFTP: sftp://[user@]host:port/path + the UC connection."""
    out = [HEADER.format(rid=rid, version=version, hash=config_hash[:16])]
    for o in cfg["objects"]:
        opts = o.get("options") or {}
        fmt = opts.get("format", "csv")
        path = opts.get("path") or f"/{o['table']}"
        if sftp:
            user = f"{sftp['user']}@" if sftp.get("user") else ""
            uri = f"sftp://{user}{sftp['host']}:{sftp.get('port', '22')}{path if path.startswith('/') else '/' + path}"
        else:
            uri = path
        reader = {"cloudFiles.format": fmt, "cloudFiles.inferColumnTypes": "true", "cloudFiles.schemaEvolutionMode": "addNewColumns"}
        if fmt == "csv":
            reader["header"] = "true" if opts.get("header", True) else "false"
        if fmt == "json" and opts.get("multiline"):
            reader["multiLine"] = "true"
        if sftp:
            reader["databricks.connection"] = sftp["connection"]
        name = table_name(o)
        out.append(f'''

@dp.table(name={name!r}, comment={_comment(rid, cfg)!r}, table_properties={{"dis.request": {rid!r}}})
def {_ident(name)}():
    reader = spark.readStream.format("cloudFiles")
    for k, v in {reader!r}.items():
        reader = reader.option(k, v)
    return reader.load({uri!r}).selectExpr("*", "_metadata.file_path AS _source_file", "current_timestamp() AS _ingested_at")
''')
    return "".join(out)


def api(rid: str, version: int, config_hash: str, cfg: dict[str, Any], table_name, connection: str) -> str:
    """One materialized view per endpoint: each run calls the API through the UC HTTP connection (the pipeline runs
    as the service principal, which holds USE CONNECTION) and lands the response with ingested_at and payload VARIANT."""
    out = [HEADER.format(rid=rid, version=version, hash=config_hash[:16]), '''import json
from datetime import datetime, timezone


def _call(connection, method, path, params):
    try:  # Databricks SDK: /api/2.0/external-function through the connection
        from databricks.sdk import WorkspaceClient
        from databricks.sdk.service.serving import ExternalFunctionRequestHttpMethod as M
        r = WorkspaceClient().serving_endpoints.http_request(connection_name=connection, method=getattr(M, method),
                                                             path=path, params=json.dumps(params) if params else None)
        body = r.contents.read() if hasattr(r, "contents") and r.contents is not None else getattr(r, "text", b"")
        return 200, body.decode() if isinstance(body, (bytes, bytearray)) else str(body)
    except Exception:  # SQL fallback: http_request()
        q = ", ".join(f"'{k}', '{str(v).replace(chr(39), '')}'" for k, v in (params or {}).items())
        row = spark.sql(f"SELECT http_request(conn => '{connection}', method => '{method}', path => '{path}'"
                        + (f", params => map({q})" if q else "") + ") AS r").first()
        return row.r.status_code, row.r.text
''']
    for o in cfg["objects"]:
        opts = o.get("options") or {}
        path = opts.get("path") or "/"
        params = opts.get("params") or {}
        method = (opts.get("method") or "GET").upper()
        name = table_name(o)
        out.append(f'''

@dp.materialized_view(name={name!r}, comment={_comment(rid, cfg)!r}, table_properties={{"dis.request": {rid!r}}})
def {_ident(name)}():
    status, text = _call({connection!r}, {method!r}, {path!r}, {params!r})
    if status >= 400:
        raise RuntimeError(f"API {{status}}: {{text[:300]}}")
    df = spark.createDataFrame([(datetime.now(timezone.utc), {connection!r}, {path!r}, status, text)],
                               "ingested_at timestamp, connection string, path string, status int, payload string")
    return df.selectExpr("*", "parse_json(payload) AS payload_v")
''')
    return "".join(out)


def _ident(name: str) -> str:
    import re

    return "t_" + re.sub(r"[^a-zA-Z0-9_]", "_", name)
